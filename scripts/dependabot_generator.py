"""Dependabot configuration generator with restrained update grouping."""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Sequence


ALLOWED_CADENCES = {"monthly", "weekly", "daily"}
ALLOWED_ECOSYSTEMS = {"pip", "github-actions"}


def validate_dependabot_stage(stage: dict) -> dict:
    if not isinstance(stage, dict):
        raise ValueError("dependabot stage must be a dictionary")
    if stage.get("name") != "dependabot":
        raise ValueError("dependabot stage name must be 'dependabot'")

    cadence = stage.get("cadence", "monthly")
    if cadence not in ALLOWED_CADENCES:
        raise ValueError(f"invalid dependabot cadence: {cadence!r}; must be one of {sorted(ALLOWED_CADENCES)}")

    raw_ecosystems = stage.get("package_ecosystems")
    if raw_ecosystems is None:
        ecosystems = ["pip", "github-actions"]
    elif isinstance(raw_ecosystems, list):
        if not raw_ecosystems or any(not isinstance(e, str) or e not in ALLOWED_ECOSYSTEMS for e in raw_ecosystems):
            raise ValueError(f"invalid package_ecosystems; must be subset of {sorted(ALLOWED_ECOSYSTEMS)}")
        ecosystems = list(dict.fromkeys(raw_ecosystems))
    else:
        raise ValueError("package_ecosystems must be a list of strings")

    limit = stage.get("open_pull_requests_limit", 5)
    if not isinstance(limit, int) or limit < 1:
        raise ValueError("open_pull_requests_limit must be a positive integer")

    groups = stage.get("groups", True)
    if not isinstance(groups, bool) and not isinstance(groups, dict):
        raise ValueError("groups must be a boolean or dict")

    expected_sha = stage.get("expected_sha")
    if expected_sha is not None and (not isinstance(expected_sha, str) or not re.fullmatch(r"[0-9a-fA-F]{40}", expected_sha)):
        raise ValueError("expected_sha must be a 40-character blob SHA")

    return {
        "name": "dependabot",
        "cadence": cadence,
        "package_ecosystems": ecosystems,
        "open_pull_requests_limit": limit,
        "groups": groups,
        "expected_sha": expected_sha,
    }


def _render_custom_groups(groups: Dict[str, Any]) -> List[str]:
    """Render explicit Dependabot group mappings supplied by the caller."""
    lines = ["    groups:"]
    for group_name, definition in groups.items():
        if not isinstance(group_name, str) or not re.fullmatch(r"[A-Za-z0-9_-]+", group_name):
            raise ValueError(f"invalid dependabot group name: {group_name!r}")
        if isinstance(definition, list):
            if not definition or any(not isinstance(item, str) or not item.strip() for item in definition):
                raise ValueError(f"dependabot group {group_name!r} patterns must be nonempty strings")
            lines.append(f"      {group_name}:")
            lines.append("        patterns:")
            for item in definition:
                lines.append(f'          - "{item}"')
            continue
        if not isinstance(definition, dict) or not definition:
            raise ValueError(f"dependabot group {group_name!r} must be a nonempty mapping")
        lines.append(f"      {group_name}:")
        for key, value in definition.items():
            if not isinstance(key, str) or not key:
                raise ValueError(f"invalid dependabot group key: {key!r}")
            if isinstance(value, list):
                lines.append(f"        {key}:")
                for item in value:
                    lines.append(f'          - "{item}"')
            elif isinstance(value, str):
                lines.append(f'        {key}: "{value}"')
            elif isinstance(value, bool):
                lines.append(f"        {key}: {str(value).lower()}")
            elif isinstance(value, (int, float)):
                lines.append(f"        {key}: {value}")
            else:
                raise ValueError(f"unsupported dependabot group value for {key!r}")
    return lines


def render_dependabot_config(stage_or_config: dict) -> str:
    config = validate_dependabot_stage(stage_or_config)
    cadence = config["cadence"]
    limit = config["open_pull_requests_limit"]
    use_groups = config["groups"] is not False

    lines = [
        "# Dependabot configuration generated by sciflow-cicd",
        "# Proportional security: restrained cadence and grouped semver updates",
        "version: 2",
        "updates:",
    ]

    for eco in config["package_ecosystems"]:
        lines.append(f'  - package-ecosystem: "{eco}"')
        lines.append('    directory: "/"')
        lines.append("    schedule:")
        lines.append(f'      interval: "{cadence}"')
        lines.append(f"    open-pull-requests-limit: {limit}")
        if use_groups:
            groups = config["groups"]
            if isinstance(groups, dict):
                lines.extend(_render_custom_groups(groups))
            else:
                group_name = "actions" if eco == "github-actions" else f"{eco}-dependencies"
                lines.append("    groups:")
                lines.append(f"      {group_name}:")
                lines.append("        patterns:")
                lines.append('          - "*"')
                lines.append("        update-types:")
                lines.append('          - "minor"')
                lines.append('          - "patch"')

    return "\n".join(lines) + "\n"


def detect_dependabot_ecosystems(api=None, repository=None, root_dir=None, inventory=None) -> List[str]:
    """Detect package ecosystems relevant to the target repository."""
    ecosystems = ["github-actions"]
    # Check for python
    try:
        from scripts.install_github_workflows import detect_python_project
    except ImportError:
        try:
            from install_github_workflows import detect_python_project
        except ImportError:
            detect_python_project = None

    if detect_python_project and detect_python_project(api, repository, root_dir, inventory):
        ecosystems.insert(0, "pip")

    return ecosystems

